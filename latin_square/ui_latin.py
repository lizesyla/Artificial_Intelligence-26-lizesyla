# 1. STEP-BY-STEP IDDFS (same rules as LatinIDDFS._dls / solve)
# =============================================================================

class SteppingIDDFS(ls.LatinIDDFS):
    def steps(self):
        """Events: ("iter", L) ("place", k, v) ("remove", k, v) ("cutoff", k)
        ("deadend", k) ("goal", k) ("iter_end", Iteration) ("end", status)"""
        cfg = self.cfg
        errs = ls.validate_partial(self.givens)
        if errs:
            self.res = ls.Result(ls.INVALID, message="; ".join(errs))
            yield ("end", ls.INVALID)
            return
        self.res = res = ls.Result(ls.NO_SOLUTION, empty=self.E, fixed_by_symmetry=self.fixed)
        self.total = 0
        self.start = time.perf_counter()
        limit = max(0, cfg.start_depth)
        self.limit = limit
        try:
            while True:
                it = ls.Iteration(limit)
                self.it = it
                self.limit = limit
                res.iterations.append(it)
                self.rng = random.Random(cfg.seed)
                t0 = time.perf_counter()
                yield ("iter", limit)
                stop = False
                stack = []
                # ---- enter(0)
                ev, frame = self._enter(0, limit, it)
                if ev:
                    yield ev
                    if ev[0] == "goal":
                        stop = self._goal_stops()
                if frame:
                    stack.append(frame)
                while stack and not stop:
                    f = stack[-1]
                    k = f["k"]
                    if f["placed"] is not None:
                        v = f["placed"]
                        self.remove(k, v)
                        f["placed"] = None
                        yield ("remove", k, v)
                    if f["i"] < len(f["values"]):
                        v = f["values"][f["i"]]
                        f["i"] += 1
                        it.nodes += 1
                        self.total += 1
                        self._limits()
                        self.place(k, v)
                        f["placed"] = v
                        yield ("place", k, v)
                        ev, child = self._enter(k + 1, limit, it)
                        if ev:
                            yield ev
                            if ev[0] == "goal" and self._goal_stops():
                                stop = True
                        if child:
                            stack.append(child)
                    else:
                        stack.pop()
                it.seconds = time.perf_counter() - t0
                yield ("iter_end", it)
                if res.solutions:
                    res.status = ls.FOUND
                    break
                if it.cutoffs == 0:
                    res.status = ls.NO_SOLUTION
                    break
                limit += max(1, cfg.step)
        except ls._Stop as s:
            it.seconds = time.perf_counter() - t0
            res.message = str(s)
            res.status = ls.FOUND if res.solutions else ls.LIMIT_REACHED
        res.nodes = self.total
        res.elapsed = time.perf_counter() - self.start
        yield ("end", res.status)

    def _goal_stops(self):
        return not self.cfg.find_all or self.res.solutions >= self.cfg.max_solutions

    def _enter(self, k, limit, it):
        """What happens when the search arrives at depth k. Returns (event, frame)."""
        if k > it.max_depth:
            it.max_depth = k
        if k == self.E:
            self.res.solutions += 1
            if self.res.solution is None:
                self.res.solution = [row[:] for row in self.grid]
            return ("goal", k), None
        if k == limit:
            it.cutoffs += 1
            return ("cutoff", k), None
        values = self.legal(k)
        if not values:
            it.dead_ends += 1
            return ("deadend", k), None
        return None, {"k": k, "values": values, "i": 0, "placed": None}

    def run_all(self):
        for _ in self.steps():
            pass
        return self.res


def selftest() -> int:
    cases = []
    for n in range(1, 7):
        cases.append(ls.Config(n=n, time_limit=None))
    for n in (3, 4):
        cases.append(ls.Config(n=n, symmetry_breaking=False, time_limit=None))
        cases.append(ls.Config(n=n, symmetry_breaking=False, find_all=True, start_depth=n * n,
                               time_limit=None))
    for seed in range(3):
        cases.append(ls.Config(n=5, value_order="random", seed=seed, time_limit=None))
    cases += [ls.Config(n=5, find_all=True, start_depth=16, time_limit=None),
              ls.Config(n=6, step=5, time_limit=None),
              ls.Config(n=12, start_depth=121, time_limit=None),
              ls.Config(n=7, max_nodes=50_000, time_limit=None),
              ls.Config(n=4, givens=ls.parse_grid("1.../.2../..3./...4"), time_limit=None),
              ls.Config(n=3, givens=ls.parse_grid("12./..3/..."), time_limit=None),
              ls.Config(n=2, givens=[[1, 1], [0, 0]], time_limit=None)]
    ok = True
    for cfg in cases:
        ref = ls.LatinIDDFS(cfg).solve()
        vis = SteppingIDDFS(cfg).run_all()
        a = [(i.limit, i.nodes, i.cutoffs, i.dead_ends, i.max_depth) for i in ref.iterations]
        b = [(i.limit, i.nodes, i.cutoffs, i.dead_ends, i.max_depth) for i in vis.iterations]
        same = (ref.status == vis.status and a == b and ref.solution == vis.solution
                and ref.solutions == vis.solutions and ref.nodes == vis.nodes)
        ok &= same
        if not same:
            print("FAIL", cfg, ref.status, vis.status, a[-3:], b[-3:])
    print(f"{len(cases)} cases compared.  SELFTEST", "PASSED" if ok else "FAILED")
    return 0 if ok else 1


