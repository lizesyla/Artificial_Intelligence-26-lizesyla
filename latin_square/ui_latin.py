#!/usr/bin/env python3
"""
Latin Square - visualizer for IDDFS with Backtracking (tkinter)
===============================================================

    python ui_latin.py              # open the window
    python ui_latin.py --selftest   # check: visual search == latin_square.solve()

SteppingIDDFS inherits LatinIDDFS (same cells, same legal values, same
place/remove, same limits) and only replaces the recursive _dls() with a loop
that pauses after every event. The self test checks that every iteration has
the same number of nodes, cutoffs, dead ends and the same solution.

What you see
  * Grid: grey bold = fixed by symmetry breaking / given, blue = placed by the
    search, yellow = the cell being filled now. Cells shaded with grey stripes
    are BEYOND the current depth limit L: the depth-limited search is not
    allowed to reach them in this iteration.
    Purple frame = CUTOFF (the limit stopped the search here),
    red frame = DEAD END (no legal number), orange = BACKTRACK (number removed).
  * Iterations table and bar chart: nodes generated by each DLS iteration.
    All earlier iterations end without a solution - that is the price of IDDFS.
"""

